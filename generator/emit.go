package main

import (
	"fmt"
	"go/format"
	"strings"
)

// generatedMarker marks every file kflare-gen writes. Go's tools, linters
// included, treat a file carrying it as generated.
const generatedMarker = "// Code generated by kflare-gen. DO NOT EDIT."

// commentWidth is how long kflare-gen's own documentation lines get, comment
// marker included, matching the hand-written API types.
const commentWidth = 80

// emitTypes returns the Go source of a kind's API types: its claim label,
// spec, status, root and list types, condition accessors and registration.
// header is the license header every Go file starts with.
func emitTypes(k *kind, header string) ([]byte, error) {
	var b strings.Builder
	write := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	write("%s\n\n%s\n\npackage v1alpha1\n\n", strings.TrimRight(header, "\n"), generatedMarker)
	write("import (\n\tcorev1 %q\n\tmetav1 %q\n)\n\n", "k8s.io/api/core/v1", "k8s.io/apimachinery/pkg/apis/meta/v1")

	comment(&b, "", wrap(fmt.Sprintf("%sIDLabel holds the ID of the Cloudflare %s a %s manages. kflare sets it, "+
		"and never adopts a %s that another %s already carries in this label.", k.name, k.noun, k.name, k.noun, k.name)))
	write("const %sIDLabel = %q\n\n", k.name, k.claimLabel)

	comment(&b, "", []string{fmt.Sprintf("%sSpec defines the desired state of %s.", k.name, k.name)})
	comment(&b, "", k.specRules)
	write("type %sSpec struct {\n", k.name)
	writeFields(&b, k.spec, true)
	write("}\n\n")

	metadataDoc := "holds identifiers returned by the Cloudflare API."
	if len(k.metadata) > 1 {
		metadataDoc = "holds identifiers and metadata returned by the Cloudflare API."
	}
	comment(&b, "", wrap(fmt.Sprintf("%sCloudflareMetadata %s", k.name, metadataDoc)))
	write("type %sCloudflareMetadata struct {\n", k.name)
	writeFields(&b, k.metadata, false)
	write("}\n\n")

	comment(&b, "", []string{fmt.Sprintf("%sStatus defines the observed state of %s.", k.name, k.name)})
	write("type %sStatus struct {\n", k.name)
	// One line each, as in the hand-written types: controller-gen keeps a
	// field's line breaks in its CRD description.
	comment(&b, "\t", []string{fmt.Sprintf("Conditions represent the latest available observations of the %s state.",
		k.noun)})
	write("\t// +listType=map\n\t// +listMapKey=type\n")
	write("\tConditions []metav1.Condition `json:\"conditions,omitempty\"`\n\n")
	comment(&b, "\t", []string{"CloudflareMetadata " + metadataDoc})
	write("\tCloudflareMetadata %sCloudflareMetadata `json:\"cloudflareMetadata,omitempty\"`\n}\n\n", k.name)

	write("// +kubebuilder:object:root=true\n// +kubebuilder:subresource:status\n")
	write("// +kubebuilder:resource:path=%s,scope=Namespaced,shortName=%s\n", k.plural, k.shortName)
	for _, c := range k.printColumns {
		write("// +kubebuilder:printcolumn:name=%q,type=%s,JSONPath=`%s`\n", c.name, c.typ, c.jsonPath)
	}
	write("\n")
	comment(&b, "", k.doc)
	write("type %s struct {\n", k.name)
	write("\tmetav1.TypeMeta   `json:\",inline\"`\n\tmetav1.ObjectMeta `json:\"metadata,omitempty\"`\n\n")
	write("\tSpec   %sSpec   `json:\"spec,omitempty\"`\n", k.name)
	write("\tStatus %sStatus `json:\"status,omitempty\"`\n}\n\n", k.name)

	write("// +kubebuilder:object:root=true\n\n// %sList contains a list of %s.\n", k.name, k.name)
	write("type %sList struct {\n", k.name)
	write("\tmetav1.TypeMeta `json:\",inline\"`\n\tmetav1.ListMeta `json:\"metadata,omitempty\"`\n")
	write("\tItems []%s `json:\"items\"`\n}\n\n", k.name)

	write("// GetConditions returns the %s's status conditions.\n", k.noun)
	write("func (in *%s) GetConditions() []metav1.Condition { return in.Status.Conditions }\n\n", k.name)
	write("// SetConditions replaces the %s's status conditions.\n", k.noun)
	write("func (in *%s) SetConditions(c []metav1.Condition) { in.Status.Conditions = c }\n\n", k.name)
	write("func init() {\n\tregister(&%s{}, &%sList{})\n}\n", k.name, k.name)

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting %s's types: %w", k.name, err)
	}
	return src, nil
}

// writeFields writes a struct's fields, a blank line between two. A spec's
// optional fields are marked +optional.
func writeFields(b *strings.Builder, fields []field, spec bool) {
	for i, f := range fields {
		if i > 0 {
			b.WriteString("\n")
		}
		comment(b, "\t", f.doc)
		if spec && f.optional {
			b.WriteString("\t// +optional\n")
		}
		comment(b, "\t", f.markers())
		tag := f.jsonName
		if f.optional {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "\t%s %s `json:\"%s\"`\n", f.goName, f.goType, tag)
	}
}

// comment writes lines as a line comment, each after indent.
func comment(b *strings.Builder, indent string, lines []string) {
	for _, line := range lines {
		if line == "" {
			b.WriteString(indent + "//\n")
			continue
		}
		b.WriteString(indent + "// " + line + "\n")
	}
}

// wrap breaks text into lines of at most commentWidth characters once
// commented, breaking between words.
func wrap(text string) []string {
	return wrapAt(text, commentWidth-len("// "))
}

// wrapIndented wraps text for a comment one tab in, a tab counting as four
// characters.
func wrapIndented(text string) []string {
	return wrapAt(text, commentWidth-len("    // "))
}

// wrapAt breaks text into lines of at most width characters, breaking
// between words.
func wrapAt(text string, width int) []string {
	var out []string
	line := ""
	for word := range strings.FieldsSeq(text) {
		if line != "" && len(line)+1+len(word) > width {
			out = append(out, line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += word
	}
	if line != "" {
		out = append(out, line)
	}
	return out
}
