// write writes the outputs into the repository at root: it removes the
// generated files of kinds no longer listed, writes every file, and rewrites
// the blocks of the files kflare-gen edits.
func (o *outputs) write(root string) error {
	for _, pattern := range stalePatterns {
		matches, err := filepath.Glob(filepath.Join(root, pattern))
		if err != nil {
			return err
		}
		for _, path := range matches {
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			if _, ok := o.files[filepath.ToSlash(rel)]; ok {
				continue
			}
			generated, err := isGenerated(path)
			if err != nil {
				return err
			}
			if generated {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
		}
	}
	for path, src := range o.files {
		if err := os.WriteFile(filepath.Join(root, path), src, 0o644); err != nil {
			return err
		}
	}
	for path, lines := range o.blocks {
		full := filepath.Join(root, path)
		src, err := os.ReadFile(full)
		if err != nil {
			return err
		}
		updated, err := replaceBlock(src, lines)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if err := os.WriteFile(full, updated, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// isGenerated reports whether the file at path is one kflare-gen wrote.
func isGenerated(path string) (bool, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	return bytes.Contains(src, []byte(generatedMarker)) || bytes.HasPrefix(src, []byte(generatedSample)), nil
}

// replaceBlock returns src with the lines between its block's markers
// replaced by lines, indented as the begin marker is.
func replaceBlock(src []byte, lines []string) ([]byte, error) {
	all := strings.SplitAfter(string(src), "\n")
	begin, end := -1, -1
	for i, line := range all {
		switch {
		case strings.Contains(line, blockBegin):
			if begin >= 0 {
				return nil, fmt.Errorf("two lines hold %s", blockBegin)
			}
			begin = i
		case strings.Contains(line, blockEnd):
			if end >= 0 {
				return nil, fmt.Errorf("two lines hold %s", blockEnd)
			}
			end = i
		}
	}
	if begin < 0 || end < begin {
		return nil, fmt.Errorf("no block: a line holding %s, then one holding %s", blockBegin, blockEnd)
	}
	indent := all[begin][:len(all[begin])-len(strings.TrimLeft(all[begin], " \t"))]
	// A line the block holds must not stand above it too: kustomize refuses a
	// resource listed twice.
	for _, line := range all[:begin] {
		if slices.Contains(lines, strings.TrimSpace(line)) {
			return nil, fmt.Errorf("%q stands outside the block that holds it: remove it", strings.TrimSpace(line))
		}
	}
	var b strings.Builder
	for _, line := range all[:begin+1] {
		b.WriteString(line)
	}
	for _, line := range lines {
		b.WriteString(indent + line + "\n")
	}
	for _, line := range all[end:] {
		b.WriteString(line)
	}
	return []byte(b.String()), nil
}
