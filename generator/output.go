// Where kflare-gen writes, relative to the repository's root. Each kind has
// a types file, a controller, its envtest table and a sample; kindsFile
// registers the kinds, and the blocks of crdKustomization and helmRBAC list
// them.
const (
	apiDir           = "api/v1alpha1"
	controllerDir    = "internal/controller"
	samplesDir       = "config/samples"
	kindsFile        = controllerDir + "/zz_generated_kinds.go"
	crdKustomization = "config/crd/kustomization.yaml"
	helmRBAC         = "helm/kflare/templates/rbac.yaml"
)

// generatedSample marks every sample kflare-gen writes.
const generatedSample = "# Generated by kflare-gen"

// The markers around the block of a file that kflare-gen keeps. The lines
// between them are kflare-gen's; the rest of the file is not.
const (
	blockBegin = "+kflare-gen:begin"
	blockEnd   = "+kflare-gen:end"
)

// outputs is what kflare-gen writes, by path relative to the repository's
// root.
type outputs struct {
	// files holds whole files.
	files map[string][]byte
	// blocks holds the lines of the block kflare-gen keeps in a file it
	// edits.
	blocks map[string][]string
}

// typesFile, controllerFile, controllerTestFile and sampleFile are the paths
// of a kind's files.
func typesFile(lowerKind string) string {
	return apiDir + "/zz_generated." + lowerKind + "_types.go"
}

func controllerFile(lowerKind string) string {
	return controllerDir + "/zz_generated." + lowerKind + ".go"
}

func controllerTestFile(lowerKind string) string {
	return controllerDir + "/zz_generated." + lowerKind + "_test.go"
}

func sampleFile(lowerKind string) string {
	return samplesDir + "/cloudflare_v1alpha1_" + lowerKind + ".yaml"
}

// stalePatterns match the files kflare-gen writes for a kind: one that
// carries its marker but that it no longer writes is removed.
var stalePatterns = []string{
	typesFile("*"), controllerFile("*"), controllerTestFile("*"), sampleFile("*"),
}

// addKind adds a kind's files.
func (o *outputs) addKind(c *controller, header string) error {
	lower := strings.ToLower(c.name)
	types, err := emitTypes(c.kind, header)
	if err != nil {
		return err
	}
	ctrl, err := emitController(c, header)
	if err != nil {
		return err
	}
	test, err := emitControllerTest(c, header)
	if err != nil {
		return err
	}
	sample, err := emitSample(c)
	if err != nil {
		return err
	}
	o.files[typesFile(lower)] = types
	o.files[controllerFile(lower)] = ctrl
	o.files[controllerTestFile(lower)] = test
	o.files[sampleFile(lower)] = sample
	return nil
}

