// Command chartannotations writes the Artifact Hub annotations of the Helm
// chart that change with the code: the controller image at the chart's
// version, the CRDs, an example of each, and the release's changes from
// CHANGELOG.md. It replaces everything after the marker line in Chart.yaml's
// annotations, so the hand-written annotations above the marker stay as they
// are. Run it from the repository's root, through make helm, after
// controller-gen has written the CRDs.
//
// Artifact Hub refuses a whole chart version over one annotation it cannot
// read, which would hide the release. So the command fails rather than write
// a change without a description or a link without a name, or an annotation
// that does not read back as written, and its tests check the committed
// annotations, the hand-written ones included, as Artifact Hub does.
// Reference: https://artifacthub.io/docs/topics/annotations/helm/
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/url"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	utilyaml "k8s.io/apimachinery/pkg/util/yaml"
	"sigs.k8s.io/yaml"
)

// The repository's paths, relative to its root.
const (
	chartPath     = "helm/kflare/Chart.yaml"
	valuesPath    = "helm/kflare/values.yaml"
	releasePath   = ".github/workflows/release.yml"
	crdDir        = "config/crd/bases"
	samplesDir    = "config/samples"
	changelogPath = "CHANGELOG.md"
)

// marker ends the hand-written annotations in Chart.yaml. Everything after it
// is this command's.
const marker = "  # Generated by hack/chartannotations (make helm). DO NOT EDIT below this line."

func main() {
	flags := flag.NewFlagSet("chartannotations", flag.ContinueOnError)
	root := flags.String("root", ".", "the repository whose chart to annotate")
	err := flags.Parse(os.Args[1:])
	if err == nil {
		err = run(*root)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "chartannotations:", err)
		os.Exit(1)
	}
}

// run rewrites the generated annotations of the chart in the repository at
// root.
func run(root string) error {
	read := func(p string) ([]byte, error) { return os.ReadFile(filepath.Join(root, p)) }
	chartYAML, err := read(chartPath)
	if err != nil {
		return err
	}
	var chart struct {
		Version    string `json:"version"`
		AppVersion string `json:"appVersion"`
		Home       string `json:"home"`
	}
	if err := yaml.Unmarshal(chartYAML, &chart); err != nil {
		return fmt.Errorf("%s: %w", chartPath, err)
	}
	valuesYAML, err := read(valuesPath)
	if err != nil {
		return err
	}
	var values struct {
		Image struct {
			Repository string `json:"repository"`
		} `json:"image"`
	}
	if err := yaml.Unmarshal(valuesYAML, &values); err != nil {
		return fmt.Errorf("%s: %w", valuesPath, err)
	}
	if values.Image.Repository == "" || chart.AppVersion == "" {
		return fmt.Errorf("the image needs %s's image.repository and %s's appVersion", valuesPath, chartPath)
	}
	release, err := read(releasePath)
	if err != nil {
		return err
	}
	platforms, err := releasePlatforms(release)
	if err != nil {
		return fmt.Errorf("%s: %w", releasePath, err)
	}
	crds, err := readCRDs(filepath.Join(root, crdDir))
	if err != nil {
		return err
	}
	examples, err := readExamples(filepath.Join(root, samplesDir), crds)
	if err != nil {
		return err
	}
	changelog, err := read(changelogPath)
	if err != nil {
		return err
	}
	changes, err := releaseChanges(changelog, chart.Version, chart.Home)
	if err != nil {
		return fmt.Errorf("%s: %w", changelogPath, err)
	}

	images := []image{{
		Name:      path.Base(values.Image.Repository),
		Image:     values.Image.Repository + ":" + chart.AppVersion,
		Platforms: platforms,
	}}
	annotations := []annotation{
		{"artifacthub.io/changes", changes},
		{"artifacthub.io/crds", crds},
		{"artifacthub.io/crdsExamples", examples},
		{"artifacthub.io/images", images},
	}
	out, err := annotate(chartYAML, annotations)
	if err != nil {
		return fmt.Errorf("%s: %w", chartPath, err)
	}
	return os.WriteFile(filepath.Join(root, chartPath), out, 0o644)
}

// An annotation is one of Chart.yaml's generated annotations. Artifact Hub
// reads each value as YAML.
type annotation struct {
	key   string
	value any
}

// image is an entry of artifacthub.io/images. Artifact Hub scans each image
// for its security report.
type image struct {
	Name      string   `json:"name"`
	Image     string   `json:"image"`
	Platforms []string `json:"platforms"`
}

// crd is an entry of artifacthub.io/crds. Artifact Hub's page shows one card
// per entry, with the example of the same kind from artifacthub.io/crdsExamples.
type crd struct {
	Kind        string `json:"kind"`
	Version     string `json:"version"`
	Name        string `json:"name"`
	DisplayName string `json:"displayName"`
	Description string `json:"description"`

	group string
}

// change is an entry of artifacthub.io/changes: Artifact Hub shows the
// description as plain text and the links below it.
type change struct {
	Description string `json:"description"`
	Links       []link `json:"links,omitempty"`
}

type link struct {
	Name string `json:"name"`
	URL  string `json:"url"`
}

// platformsRE matches the platforms the release workflow builds the image for.
var platformsRE = regexp.MustCompile(`(?m)^[ \t]+platforms:[ \t]*(\S+)[ \t]*$`)

// releasePlatforms returns the platforms the release workflow builds the
// controller image for.
func releasePlatforms(workflow []byte) ([]string, error) {
	matches := platformsRE.FindAllSubmatch(workflow, -1)
	if len(matches) != 1 {
		return nil, fmt.Errorf("want one platforms line for the image, found %d", len(matches))
	}
	return strings.Split(string(matches[0][1]), ","), nil
}

// readCRDs returns the CRDs controller-gen wrote into dir, sorted by kind.
func readCRDs(dir string) ([]crd, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil {
		return nil, err
	}
	crds := make([]crd, 0, len(files))
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return nil, err
		}
		var def apiextensionsv1.CustomResourceDefinition
		if err := yaml.Unmarshal(data, &def); err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		kind := def.Spec.Names.Kind
		i := slices.IndexFunc(def.Spec.Versions, func(v apiextensionsv1.CustomResourceDefinitionVersion) bool {
			return v.Storage
		})
		if i < 0 || def.Spec.Versions[i].Schema == nil || def.Spec.Versions[i].Schema.OpenAPIV3Schema == nil {
			return nil, fmt.Errorf("%s: no stored version with a schema", file)
		}
		version := def.Spec.Versions[i]
		description, err := summary(kind, version.Schema.OpenAPIV3Schema.Description)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		crds = append(crds, crd{
			Kind:        kind,
			Version:     version.Name,
			Name:        def.Name,
			DisplayName: kind,
			Description: description,
			group:       def.Spec.Group,
		})
	}
	if len(crds) == 0 {
		return nil, fmt.Errorf("%s holds no CRDs", dir)
	}
	slices.SortFunc(crds, func(a, b crd) int { return strings.Compare(a.Kind, b.Kind) })
	return crds, nil
}

// summary returns the first sentence of a kind's description, the one after
// the "<Kind> is the Schema for the <plural> API." line kubebuilder's types
// start with. The kind's types begin it with "It", which becomes the kind's
// name, since Artifact Hub shows the sentence on its own.
func summary(kind, description string) (string, error) {
	first, rest, _ := strings.Cut(description, "\n")
	if strings.HasPrefix(first, kind+" is the Schema for the ") {
		description = rest
	}
	text := strings.Join(strings.Fields(description), " ")
	if text == "" {
		return "", fmt.Errorf("%s has no description", kind)
	}
	if end := strings.Index(text, ". "); end >= 0 {
		text = text[:end+1]
	}
	if after, ok := strings.CutPrefix(text, "It "); ok {
		text = kind + " " + after
	}
	return text, nil
}

// readExamples returns an example of each kind in crds: the first resource of
// the kind in its sample file, config/samples/cloudflare_v1alpha1_<kind>.yaml,
// or, for a kind with several, the first of
// config/samples/cloudflare_v1alpha1_<kind>_*.yaml. Artifact Hub shows only
// one example per kind.
func readExamples(dir string, crds []crd) ([]map[string]any, error) {
	examples := make([]map[string]any, 0, len(crds))
	for _, c := range crds {
		base := filepath.Join(dir, "cloudflare_v1alpha1_"+strings.ToLower(c.Kind))
		files, err := filepath.Glob(base + "_*.yaml")
		if err != nil {
			return nil, err
		}
		if _, err := os.Stat(base + ".yaml"); err == nil {
			files = []string{base + ".yaml"}
		}
		if len(files) == 0 {
			return nil, fmt.Errorf("%s has no sample in %s", c.Kind, dir)
		}
		example, err := firstOfKind(files[0], c.group+"/"+c.Version, c.Kind)
		if err != nil {
			return nil, err
		}
		examples = append(examples, example)
	}
	return examples, nil
}

// firstOfKind returns the first resource of the kind and API version in the
// YAML documents of file.
func firstOfKind(file, apiVersion, kind string) (map[string]any, error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return nil, err
	}
	docs := utilyaml.NewYAMLReader(bufio.NewReader(bytes.NewReader(data)))
	for {
		doc, err := docs.Read()
		if errors.Is(err, io.EOF) {
			return nil, fmt.Errorf("%s holds no %s %s", file, apiVersion, kind)
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		var obj map[string]any
		if err := yaml.Unmarshal(doc, &obj); err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		if obj["apiVersion"] == apiVersion && obj["kind"] == kind {
			return obj, nil
		}
	}
}

// skippedSections are CHANGELOG.md's subsections that list steps or caveats
// rather than changes.
var skippedSections = []string{"Upgrading", "Known limitations", "Coming in"}

var (
	kindSectionRE = regexp.MustCompile("^### `([A-Za-z0-9]+)`$")
	markdownLink  = regexp.MustCompile(`\[([^\]]+)\]\(([^)\s]+)\)`)
)

// releaseChanges returns the changes of version from CHANGELOG.md: the
// bullets of its section, but for those in skippedSections. A bullet in a
// kind's section ("### `Kind`") starts with the kind. Each loses its
// Markdown, as Artifact Hub shows plain text on one line: the items of a
// list nested in it follow its text, separated by semicolons, and its links
// go to the change's links, made absolute against the release's tag in the
// repository at home.
func releaseChanges(changelog []byte, version, home string) ([]change, error) {
	if version == "" || home == "" {
		return nil, fmt.Errorf("the changes need the chart's version and home")
	}
	base, err := url.Parse(strings.TrimSuffix(home, "/") + "/blob/v" + version + "/" + changelogPath)
	if err != nil {
		return nil, err
	}
	heading := regexp.MustCompile(`^## v` + regexp.QuoteMeta(version) + `(\s.*)?$`)

	var (
		changes          []change
		bullet           []string
		found, inSection bool
		skip, inFence    bool
		prefix           string
		nestedItems      int
	)
	flush := func() error {
		if bullet == nil {
			return nil
		}
		c, err := plainChange(prefix+strings.Join(bullet, " "), base)
		if err != nil {
			return err
		}
		changes = append(changes, c)
		bullet = nil
		return nil
	}
	for line := range strings.Lines(string(changelog)) {
		line = strings.TrimRight(line, "\r\n")
		if !inSection {
			if heading.MatchString(line) {
				found, inSection = true, true
			}
			continue
		}
		if strings.HasPrefix(line, "```") {
			inFence = !inFence
		}
		switch {
		case inFence || strings.HasPrefix(line, "```"):
			// Code blocks hold manifests, not changes; a bullet ends before one.
			if err := flush(); err != nil {
				return nil, err
			}
		case strings.HasPrefix(line, "## "):
			inSection = false
		case strings.HasPrefix(line, "### "):
			if err := flush(); err != nil {
				return nil, err
			}
			title := strings.TrimPrefix(line, "### ")
			skip = slices.ContainsFunc(skippedSections, func(s string) bool { return strings.HasPrefix(title, s) })
			prefix = ""
			if m := kindSectionRE.FindStringSubmatch(line); m != nil {
				prefix = m[1] + ": "
			}
		case strings.HasPrefix(line, "- "):
			if err := flush(); err != nil {
				return nil, err
			}
			if !skip {
				bullet, nestedItems = []string{strings.TrimPrefix(line, "- ")}, 0
			}
		case bullet != nil && strings.HasPrefix(line, "  ") && strings.TrimSpace(line) != "":
			text := strings.TrimSpace(line)
			if item, ok := strings.CutPrefix(text, "- "); ok {
				if nestedItems > 0 {
					bullet[len(bullet)-1] += ";"
				}
				nestedItems++
				text = item
			}
			bullet = append(bullet, text)
		default:
			if err := flush(); err != nil {
				return nil, err
			}
		}
		if !inSection {
			break
		}
	}
	if err := flush(); err != nil {
		return nil, err
	}
	if !found {
		return nil, fmt.Errorf("no section for v%s", version)
	}
	if len(changes) == 0 {
		return nil, fmt.Errorf("v%s's section lists no changes", version)
	}
	return changes, nil
}

// plainChange returns a change from a CHANGELOG.md bullet: its text without
// bold markers and links, which become the change's links, resolved against
// base.
func plainChange(text string, base *url.URL) (change, error) {
	text = strings.ReplaceAll(text, "**", "")
	var links []link
	var linkErr error
	text = markdownLink.ReplaceAllStringFunc(text, func(m string) string {
		parts := markdownLink.FindStringSubmatch(m)
		ref, err := url.Parse(parts[2])
		if err != nil {
			linkErr = errors.Join(linkErr, fmt.Errorf("link %q: %w", parts[2], err))
			return parts[1]
		}
		target := base.ResolveReference(ref).String()
		if !slices.ContainsFunc(links, func(l link) bool { return l.URL == target }) {
			links = append(links, link{Name: parts[1], URL: target})
		}
		return parts[1]
	})
	if linkErr != nil {
		return change{}, linkErr
	}
	if strings.TrimSpace(text) == "" {
		return change{}, errors.New("a change without a description")
	}
	return change{Description: text, Links: links}, nil
}

// annotate returns chart, the Chart.yaml, with everything after the marker
// line replaced by the annotations. It refuses a chart with keys of its own
// after the generated annotations, which it would drop, and checks that the
// result reads back with each annotation's value.
func annotate(chart []byte, annotations []annotation) ([]byte, error) {
	head, tail, found := bytes.Cut(chart, []byte(marker+"\n"))
	if !found {
		return nil, fmt.Errorf("no marker line %q", marker)
	}
	for line := range strings.Lines(string(tail)) {
		if strings.TrimSpace(line) != "" && !strings.HasPrefix(line, "  ") {
			return nil, fmt.Errorf("%q follows the generated annotations: keep annotations the last key", line)
		}
	}
	var out bytes.Buffer
	out.Write(head)
	out.WriteString(marker + "\n")
	want := map[string]string{}
	for _, a := range annotations {
		value, err := yaml.Marshal(a.value)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", a.key, err)
		}
		want[a.key] = string(value)
		fmt.Fprintf(&out, "  %s: |\n", a.key)
		for line := range strings.Lines(string(value)) {
			if strings.TrimSpace(line) != "" {
				out.WriteString("    ")
			}
			out.WriteString(line)
		}
	}

	var got struct {
		Annotations map[string]string `json:"annotations"`
	}
	if err := yaml.Unmarshal(out.Bytes(), &got); err != nil {
		return nil, fmt.Errorf("the annotated chart does not parse: %w", err)
	}
	for key, value := range want {
		if got.Annotations[key] != value {
			return nil, fmt.Errorf("%s reads back as %q, not %q", key, got.Annotations[key], value)
		}
	}
	return out.Bytes(), nil
}
